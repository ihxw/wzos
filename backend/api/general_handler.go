package api

import (
	"net/http"

	"github.com/gin-gonic/gin"
	"github.com/wzos/backend/core"
)

type GeneralHandler struct {
	Service *core.GeneralService
}

func NewGeneralHandler(service *core.GeneralService) *GeneralHandler {
	return &GeneralHandler{Service: service}
}

func (h *GeneralHandler) GetSettings(c *gin.Context) {
	settings, err := h.Service.GetSettings()
	if err != nil {
		c.JSON(http.StatusInternalServerError, gin.H{"error": err.Error()})
		return
	}
	c.JSON(http.StatusOK, settings)
}

func (h *GeneralHandler) SetHostname(c *gin.Context) {
	var req struct {
		Hostname string `json:"hostname"`
	}
	if err := c.ShouldBindJSON(&req); err != nil {
		c.JSON(http.StatusBadRequest, gin.H{"error": "invalid request"})
		return
	}
	if err := h.Service.SetHostname(req.Hostname); err != nil {
		c.JSON(http.StatusInternalServerError, gin.H{"error": err.Error()})
		return
	}
	c.JSON(http.StatusOK, gin.H{"ok": true})
}

